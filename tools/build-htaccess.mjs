// ============================================================
// Writes dist/.htaccess for the production Apache server.
//
// The redirect table lives in src/data/redirects.js and is used
// by server.mjs locally; this reproduces it in the form Apache
// reads, so the two can never drift. Run after build.mjs.
// ============================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REDIRECTS } from '../src/data/redirects.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');

// The canonical origin, taken from the same value the pages are built with
// so the redirect and the <link rel="canonical"> can never disagree.
const SITE_URL = process.env.SITE_URL || 'https://www.erasmusinbarcelona.com';
const { protocol, host } = new URL(SITE_URL);
if (protocol !== 'https:') throw new Error(`SITE_URL must be https: ${SITE_URL}`);
const wantsWww = host.startsWith('www.');

// RedirectMatch with an anchored pattern, not Redirect: Redirect matches
// on prefix, so `/home` would also catch `/home/` and send it to `//`,
// and any future path beginning with a legacy one would be swallowed too.
//
// The target is absolute, and that is not cosmetic. Apache expands a
// relative Redirect target into an absolute Location using its own idea
// of the scheme — and Varnish terminates TLS in front of it, so its own
// idea is always http. A relative target therefore sends every legacy
// URL to http://, which the scheme rule above then answers with a
// second 301 to https://. Two hops, the first in the clear, for exactly
// the URLs the old site had indexed. Measured on the live site on
// 22 August 2026: /about-us/ and /program-information/ both handed back
// http:// Locations. Writing SITE_URL in makes it one hop again.
const redirects = Object.entries(REDIRECTS)
  .map(([from, to]) => `  RedirectMatch 301 ^${from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$ ${SITE_URL}${to}`)
  .join('\n');

const htaccess = `# ============================================================
# erasmusinbarcelona.com — Apache configuration for the static build.
#
# Reproduces server.mjs in production: the legacy redirect table,
# directory URLs with a trailing slash, and 404.html served with a
# real 404 status.
#
# Generated by tools/build-htaccess.mjs. Edit src/data/redirects.js
# and rebuild; never edit this file on the server.
# ============================================================

Options -Indexes
DirectoryIndex index.html
DirectorySlash On
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # One canonical origin: ${SITE_URL}, in two separate rules.
  #
  # The scheme rule has to consult X-Forwarded-Proto, not just HTTPS.
  # Varnish sits in front of Apache and terminates TLS, so %{HTTPS} is
  # always "off" here however the visitor arrived. Testing it alone
  # sends every HTTPS request a redirect to HTTPS, which the proxy
  # answers by forwarding plain HTTP again: ERR_TOO_MANY_REDIRECTS, and
  # a site that is completely unreachable rather than merely wrong.
  #
  # The hosting's own *.dinaserver.com name is exempt from both, so the
  # site can be opened and checked there before the domain points here.
  # HTTP_HOST carries the port when there is a non-default one, so the
  # exemption has to allow for it or it silently stops applying.
  RewriteCond %{HTTP_HOST} !\\.dinaserver\\.com(:[0-9]+)?$ [NC]
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !=https
  RewriteRule ^(.*)$ ${SITE_URL}/$1 [R=301,L]

  RewriteCond %{HTTP_HOST} !\\.dinaserver\\.com(:[0-9]+)?$ [NC]
  RewriteCond %{HTTP_HOST} ${wantsWww ? '!^www\\.' : '^www\\.'} [NC]
  RewriteRule ^(.*)$ ${SITE_URL}/$1 [R=301,L]
</IfModule>

# Legacy paths from the previous site. One hop only — no chains.
<IfModule mod_alias.c>
${redirects}
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  # HTML is rebuilt on every deploy; assets carry content in their names.
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  <FilesMatch "\\.(css|js|webp|jpg|jpeg|png|svg|ico|woff2)$">
    Header set Cache-Control "public, max-age=31536000"
  </FilesMatch>
</IfModule>

<IfModule mod_mime.c>
  AddType image/webp .webp
  AddType image/svg+xml .svg
  AddCharset UTF-8 .html .css .js .json .xml .txt
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript \\
    application/javascript application/json image/svg+xml text/xml application/xml
</IfModule>
`;

fs.writeFileSync(path.join(DIST, '.htaccess'), htaccess);
console.log(`dist/.htaccess → ${host} canonical · ${Object.keys(REDIRECTS).length} legacy redirects`);
